#!/usr/bin/env python3
"""Copies android_overlay/ over the generated android/ and patches the manifest.

android/ is regenerated by `flutter create` on every CI run, so everything
native lives in android_overlay/ and is applied here. Idempotent.
"""
import pathlib
import shutil
import sys

root = pathlib.Path(__file__).resolve().parent.parent
overlay = root / "android_overlay"
android = root / "android"
if not android.is_dir():
    sys.exit("android/ missing: run `flutter create --org co.vibit.up --project-name up .` first")

# Kotlin goes next to the generated MainActivity, in its package — which
# `flutter create` derives from --org and the project name, so it is read
# rather than assumed.
kotlin_root = android / "app/src/main/kotlin"
generated = next(kotlin_root.rglob("MainActivity.kt"), None)
if generated is None:
    sys.exit("generated MainActivity.kt not found")
package = next(
    line.split()[1] for line in generated.read_text(encoding="utf-8").splitlines()
    if line.startswith("package ")
)
for src in sorted((overlay / "kotlin").glob("*.kt")):
    dst = generated.parent / src.name
    dst.write_text(src.read_text(encoding="utf-8").replace("__PACKAGE__", package), encoding="utf-8")
    print("overlay", dst.relative_to(root), "package", package)

res = android / "app/src/main/res"
for src in (overlay / "res").rglob("*"):
    if src.is_file():
        dst = res / src.relative_to(overlay / "res")
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        print("overlay", dst.relative_to(root))

manifest = android / "app/src/main/AndroidManifest.xml"
text = manifest.read_text(encoding="utf-8")

# The phone answers as an NFC tag. Optional hardware: the app still installs on
# phones without NFC, it just shows the QR only.
head = [
    '<uses-permission android:name="android.permission.NFC"/>',
    '<uses-feature android:name="android.hardware.nfc" android:required="false"/>',
    '<uses-feature android:name="android.hardware.nfc.hce" android:required="false"/>',
]
for line in head:
    if line not in text:
        text = text.replace("<application", f"{line}\n    <application", 1)

service = """
        <service
            android:name=".CardHceService"
            android:exported="true"
            android:permission="android.permission.BIND_NFC_SERVICE">
            <intent-filter>
                <action android:name="android.nfc.cardemulation.action.HOST_APDU_SERVICE"/>
            </intent-filter>
            <meta-data
                android:name="android.nfc.cardemulation.host_apdu_service"
                android:resource="@xml/card_apdu_service"/>
        </service>
    </application>"""
if "CardHceService" not in text:
    text = text.replace("</application>", service.lstrip(), 1)

manifest.write_text(text, encoding="utf-8")
print("manifest patched")

# Release signing with UP's own key, when CI provides it. Without a fixed key
# every build is signed with a fresh debug key, and Android refuses to install
# it over the previous one ("signatures do not match").
import os
keystore = os.environ.get("UP_KEYSTORE_FILE", "")
if keystore and os.path.isfile(keystore) and os.environ.get("UP_KEYSTORE_PASSWORD"):
    kts = android / "app/build.gradle.kts"
    groovy = android / "app/build.gradle"
    if kts.is_file():
        g = kts.read_text(encoding="utf-8")
        block = """    signingConfigs {
        create("release") {
            storeFile = file(System.getenv("UP_KEYSTORE_FILE"))
            storePassword = System.getenv("UP_KEYSTORE_PASSWORD")
            keyAlias = "up"
            keyPassword = System.getenv("UP_KEYSTORE_PASSWORD")
        }
    }

    buildTypes {"""
        if 'create("release")' not in g:
            g = g.replace("    buildTypes {", block, 1)
        g = g.replace('signingConfig = signingConfigs.getByName("debug")',
                      'signingConfig = signingConfigs.getByName("release")')
        kts.write_text(g, encoding="utf-8")
        print("release signing: build.gradle.kts")
    elif groovy.is_file():
        g = groovy.read_text(encoding="utf-8")
        block = """    signingConfigs {
        release {
            storeFile file(System.getenv("UP_KEYSTORE_FILE"))
            storePassword System.getenv("UP_KEYSTORE_PASSWORD")
            keyAlias "up"
            keyPassword System.getenv("UP_KEYSTORE_PASSWORD")
        }
    }

    buildTypes {"""
        if "signingConfigs {" not in g:
            g = g.replace("    buildTypes {", block, 1)
        g = g.replace("signingConfig signingConfigs.debug", "signingConfig signingConfigs.release")
        groovy.write_text(g, encoding="utf-8")
        print("release signing: build.gradle")
else:
    print("release signing: no keystore, debug key")
